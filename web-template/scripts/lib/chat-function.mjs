/**
 * The assistant's server half for a preview host: a Vercel Node function
 * that answers the same POST the widget already makes to /chat.php.
 *
 * Same contract, same limits and the same rules as scripts/lib/chat-handler.mjs
 * (the PHP one for the client's own hosting). Two implementations exist
 * because the two hosts run different runtimes; if a rule changes, change it
 * in both — DECISIONS.md → The chat assistant, "preview host".
 *
 * Differences forced by the runtime, all documented in the code:
 *   - secrets come from the project's environment variables
 *   - rate limits are per function instance and reset when it recycles; a
 *     preview behind a noindex header does not need the PHP file's
 *     durability, and Vercel's own logs carry the usage line
 *   - the knowledge file is fetched from the deployment itself
 *
 * Uses the official SDK: this file is installed with npm at build time, so
 * there is no reason not to.
 */
export function chatFunction() {
  return `// Generated by \`pnpm deploy-vercel\`. Edits here are overwritten on the next
// deploy — change scripts/lib/chat-function.mjs instead.

const sdk = require('@anthropic-ai/sdk')
const Anthropic = sdk.default ?? sdk

const MAX_USER_TURNS = 8
const MAX_MESSAGE_CHARS = 500
const PER_IP_PER_MINUTE = 6
const PER_IP_PER_DAY = 40
const MAX_OUTPUT_TOKENS = 300
const KNOWLEDGE_TTL_MS = 5 * 60 * 1000

// Per instance. Good enough for a noindex preview; the PHP handler on the
// client's own host keeps these on disk.
const hits = new Map()
let day = { key: '', count: 0 }
let knowledge = { host: '', at: 0, data: null }

async function loadKnowledge(host) {
  if (knowledge.host === host && Date.now() - knowledge.at < KNOWLEDGE_TTL_MS) return knowledge.data
  const response = await fetch(\`https://\${host}/chatbot.json\`)
  if (!response.ok) return null
  const data = await response.json()
  knowledge = { host, at: Date.now(), data }
  return data
}

function buildSystemPrompt(k) {
  const pl = String(k.locale ?? 'en').startsWith('pl')
  const name = k.business.name
  const phone = k.contact?.phone ?? ''
  const email = k.contact?.email ?? ''

  const facts = []
  facts.push(
    (pl ? 'Firma: ' : 'Business: ') + name +
      (k.business.legalName ? \` (\${k.business.legalName})\` : '') +
      (k.business.foundedYear ? (pl ? ', od ' : ', since ') + k.business.foundedYear : '') +
      '. ' + (k.business.description ?? ''),
  )
  facts.push((pl ? 'Adres: ' : 'Address: ') + (k.contact?.address ?? ''))
  facts.push((pl ? 'Telefon: ' : 'Phone: ') + phone + (email ? (pl ? '. E-mail: ' : '. Email: ') + email : ''))
  if (k.hours?.length) facts.push((pl ? 'Godziny otwarcia: ' : 'Opening hours: ') + k.hours.join('; '))
  if (k.services?.length) {
    facts.push(pl ? 'Usługi:' : 'Services:')
    for (const s of k.services) facts.push(\`- \${s.name}: \${s.short}\`)
  }
  if (k.areas?.length) facts.push((pl ? 'Obszar działania: ' : 'Areas covered: ') + k.areas.join(', '))
  if (k.faqs?.length) {
    facts.push(pl ? 'Pytania i odpowiedzi:' : 'Questions and answers:')
    for (const f of k.faqs) facts.push(\`Q: \${f.q}\\nA: \${f.a}\`)
  }
  for (const n of k.notes ?? []) facts.push(\`- \${n}\`)

  const rules = pl
    ? \`Jesteś asystentem na stronie firmy \${name}. Odpowiadasz po polsku, krótko — najwyżej trzy zdania — i wyłącznie na podstawie FAKTÓW poniżej.
Zasady:
- Nigdy nie podawaj cen, kosztów, terminów, dostępności towaru, gwarancji ani obietnic technicznych. Takie sprawy ustala się telefonicznie lub po oględzinach — podaj numer \${phone}.
- Jeśli czegoś nie ma w faktach, powiedz wprost, że nie wiesz, i odeślij do telefonu \${phone}\${email ? \` lub e-maila \${email}\` : ''}.
- Nie zmyślaj i nie uzupełniaj faktów własną wiedzą o branży.
- Jesteś asystentem AI; jeśli ktoś pyta, powiedz to. Nie proś o dane osobowe.
- Trzymaj się tematu firmy. Zwykły tekst: bez markdown, bez list, bez nagłówków.

FAKTY:
\`
    : \`You are the assistant on the website of \${name}. Answer in English, briefly — three sentences at most — and only from the FACTS below.
Rules:
- Never give prices, costs, dates, stock availability, guarantees or technical promises. Those are settled by phone or after a site visit — give the number \${phone}.
- If the facts do not cover it, say plainly that you do not know and point to \${phone}\${email ? \` or \${email}\` : ''}.
- Do not invent, and do not fill gaps with general trade knowledge.
- You are an AI assistant; say so if asked. Do not ask for personal details.
- Stay on the business. Plain text: no markdown, no lists, no headings.

FACTS:
\`
  return rules + facts.join('\\n')
}

function cleanMessages(input) {
  const raw = Array.isArray(input?.messages) ? input.messages : []
  const clean = []
  let userTurns = 0
  for (const m of raw) {
    const role = m?.role === 'assistant' ? 'assistant' : 'user'
    // eslint-disable-next-line no-control-regex
    let text = String(m?.content ?? '').replace(/[\\x00-\\x08\\x0B\\x0C\\x0E-\\x1F]/g, '').trim()
    if (!text) continue
    text = text.slice(0, MAX_MESSAGE_CHARS)
    // The API wants alternating roles; merge a repeat into the previous turn.
    if (clean.length && clean[clean.length - 1].role === role) {
      clean[clean.length - 1].content += '\\n' + text
      continue
    }
    clean.push({ role, content: text })
    if (role === 'user') userTurns++
  }
  while (clean.length && clean[0].role !== 'user') clean.shift()
  return { clean, userTurns }
}

module.exports = async (req, res) => {
  res.setHeader('Content-Type', 'application/json; charset=utf-8')
  res.setHeader('Cache-Control', 'no-store')
  const reply = (status, body) => res.status(status).send(JSON.stringify(body))

  if (req.method !== 'POST') return reply(405, { error: 'method' })

  // Only this deployment's own pages may call this.
  const host = String(req.headers.host ?? '').toLowerCase()
  let originHost = ''
  try {
    const origin =
      req.headers.origin ||
      (req.headers['sec-fetch-site'] === 'same-origin' ? 'https://' + host : req.headers.referer)
    originHost = new URL(String(origin ?? '')).host.toLowerCase()
  } catch {
    /* no or malformed Origin */
  }
  if (!host || originHost !== host) return reply(403, { error: 'origin' })

  const apiKey = process.env.CHATBOT_API_KEY
  if (!apiKey) return reply(503, { error: 'unavailable' })
  const model = process.env.CHATBOT_MODEL || 'claude-haiku-4-5'
  const dailyLimit = Number(process.env.CHATBOT_DAILY_LIMIT || 400)

  const k = await loadKnowledge(host)
  if (!k?.business?.name) return reply(503, { error: 'no_knowledge' })

  // Limits: per visitor, then for the whole site.
  const now = Date.now()
  const ip = String(req.headers['x-forwarded-for'] ?? '').split(',')[0].trim() || req.socket?.remoteAddress || 'unknown'
  const stamps = (hits.get(ip) ?? []).filter((t) => t > now - 86_400_000)
  if (stamps.filter((t) => t > now - 60_000).length >= PER_IP_PER_MINUTE || stamps.length >= PER_IP_PER_DAY) {
    return reply(429, { error: 'rate_limited' })
  }
  const today = new Date().toISOString().slice(0, 10)
  if (day.key !== today) day = { key: today, count: 0 }
  if (day.count >= dailyLimit) return reply(429, { error: 'daily_cap' })

  const { clean, userTurns } = cleanMessages(req.body)
  if (!clean.length || clean[clean.length - 1].role !== 'user') return reply(422, { error: 'messages' })
  if (userTurns > MAX_USER_TURNS) return reply(429, { error: 'rate_limited' })

  // The visitor's request counts whether or not the model answered.
  stamps.push(now)
  hits.set(ip, stamps)
  day.count++

  const client = new Anthropic({ apiKey, baseURL: process.env.CHATBOT_API_BASE || undefined })
  try {
    const response = await client.messages.create({
      model,
      max_tokens: MAX_OUTPUT_TOKENS,
      temperature: 0.3,
      system: buildSystemPrompt(k),
      messages: clean,
    })
    const text = response.content
      .filter((block) => block.type === 'text')
      .map((block) => block.text)
      .join('')
      .trim()
    // Usage, not content — the same line the PHP handler writes to its log.
    console.log(JSON.stringify({ chat: 'usage', model, input: response.usage?.input_tokens, output: response.usage?.output_tokens }))
    return reply(200, { reply: text })
  } catch (error) {
    console.error(JSON.stringify({ chat: 'error', status: error?.status, message: String(error?.message ?? error).slice(0, 300) }))
    return reply(503, { error: 'upstream' })
  }
}
`
}
